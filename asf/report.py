"""Pull-request description: what changed, why it is safe, what it cost."""

from __future__ import annotations

from typing import Any

from .models import WorkItem

ICON = {"pass": "pass", "fail": "FAIL", "skipped": "skipped", "preexisting": "pre-existing failure"}


def render_report(job: dict[str, Any], item: WorkItem, runs: list[dict[str, Any]], cost: float) -> str:
    d = job["data"]
    decision = d.get("decision", {})
    lines = [f"## {item.title}", ""]
    src = f"{item.source_kind} `{item.external_id}`" + (f" ({item.url})" if item.url else "")
    lines += [f"Work item: {src}", f"Factory job: `{job['id']}`, risk tier **{job.get('tier')}**", ""]
    revisions = [rv for rv in d.get("revisions", []) if rv.get("commit")]
    if revisions:
        lines += ["### Revisions", ""]
        for rv in revisions:
            lines += [f"**Revision {rv['n']}** (`{rv['commit'][:10]}`), from review notes:", ""]
            lines += [f"- {n}" for n in rv["notes"]]
            lines += [""]
    lines += ["### Summary" + (" of the latest revision" if revisions else ""), "",
              (d.get("implementer") or "").strip() or "(no summary)", ""]
    acc = d.get("acceptance", [])
    met = set(d.get("acceptance_met", []))
    if acc:
        lines += ["### Acceptance criteria", ""]
        lines += [f"- [{'x' if c in met else ' '}] {c}" for c in acc]
        lines += [""]
    manual = d.get("manual_verification") or []
    if manual:
        lines += ["### Manual verification before merge", "",
                  "Automation cannot cover these. A human must check them on the branch:", ""]
        lines += [f"- [ ] {m}" for m in manual]
        lines += [""]
    lines += ["### Gates", "", "| Gate | Package | Result | Detail |", "|---|---|---|---|"]
    for g in d.get("gates", []):
        detail = str(g.get("detail", "")).replace("|", "\\|")[:160]
        lines.append(f"| {g['name']} | {g.get('package') or ''} | {ICON.get(g['status'], g['status'])} | {detail} |")
    lines += [""]
    if d.get("tester"):
        lines += ["### Independent tester", "", d["tester"].strip(), ""]
        if d.get("tests_added"):
            lines += ["Tests added: " + ", ".join(f"`{t}`" for t in d["tests_added"]), ""]
    for role, review in (d.get("reviews") or {}).items():
        lines += [f"### {role.capitalize()} review: {review.get('verdict', '?')}", "",
                  (review.get("summary") or "").strip(), ""]
        for f in review.get("findings", []):
            loc = f"{f.get('file')}:{f.get('line')}" if f.get("line") else f.get("file")
            lines.append(f"- **{f.get('severity')}** `{loc}`: {f.get('issue')}")
        lines += [""]
    lines += ["### Policy", "", f"- Merge mode for tier {job.get('tier')}: {decision.get('merge_mode')}",
              f"- Human approvals required: {decision.get('approvals_required')}",
              f"- Agent may merge: {decision.get('may_agent_merge')} ({decision.get('reason')})", ""]
    by_role: dict[str, float] = {}
    for r in runs:
        by_role[r["role"]] = by_role.get(r["role"], 0) + r["cost_usd"]
    lines += ["### Cost", "", f"Total model spend: ${cost:.2f} "
              + "(" + ", ".join(f"{k} ${v:.2f}" for k, v in by_role.items()) + ")", ""]
    lines += ["<sub>Generated by the software factory. Every agent tool call is in the job's event log "
              f"(`asf events {job['id']}`).</sub>"]
    return "\n".join(lines) + "\n"
